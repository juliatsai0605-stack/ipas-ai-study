import {chromium} from "playwright";
import assert from "node:assert/strict";

const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on("pageerror",e=>errors.push(e.message));
try{
 await page.goto("http://127.0.0.1:4173/",{waitUntil:"networkidle"});
 await page.locator("#dashContinue").waitFor({timeout:15000});
 await page.locator('.tabs [data-v="drill"]').click();
 await page.locator("#dK").selectOption("10");
 await page.locator("#dSmart").click();
 await page.locator(".q[data-id]").waitFor();
 const id=await page.locator(".q[data-id]").getAttribute("data-id");
 const correct=await page.evaluate(qid=>BANK.find(q=>String(q.id)===qid)?.a,id);
 assert.ok(Number.isInteger(correct),"test question must exist in official bank");
 const wrong=(correct+1)%4;
 await page.locator(`.q .opt[data-j="${wrong}"]`).click();
 assert.match(await page.locator(".q .after").innerText(),/答錯/);
 const history=await page.evaluate(qid=>window.IPAS_BRIDGE.snapshot().q[qid],id);
 assert.equal(history[3],0,"wrong answer must enter wrong-answer record");
 const review=await page.evaluate(qid=>window.IPAS_BRIDGE.snapshot().srs[qid],id);
 assert.equal(review.step,0,"wrong answer must reset spaced repetition");
 await page.locator("#dQuit").click();
 await page.locator("#dBack").click();
 await page.locator("#dWrong").click();
 assert.equal(await page.locator(".q[data-id]").getAttribute("data-id"),id,"wrong-answer drill must recall missed question");
 await page.locator(`.q .opt[data-j="${correct}"]`).click();
 assert.match(await page.locator(".q .after").innerText(),/答對/);
 await page.locator("#dNext").click();
 await page.locator("#dBack").click();
 await page.locator("#dWrong").click();
 assert.match(await page.locator("#main").innerText(),/目前沒有錯題/);
 await page.locator('.tabs [data-v="mock"]').click();
 const first=page.locator('button[data-sub][data-x]').first();
 await first.waitFor();
 await first.click();
 await page.locator(".q .opt").first().click();
 await page.locator("#mSubmit").click();
 const confirm=page.locator("#sy");
 if(await confirm.count())await confirm.click();
 await page.locator("#mBack").waitFor({timeout:15000});
 const result=await page.locator("#main").innerText();
 assert.match(result,/分/,"mock score must render");
 const snapshot=await page.evaluate(()=>window.IPAS_BRIDGE.snapshot());
 assert.ok(snapshot.mocks.length>=1,"mock exam score must persist in local state");
 assert.ok(Object.keys(snapshot.q).length>=1,"question history must persist");
 await page.reload({waitUntil:"networkidle"});
 const reloaded=await page.evaluate(()=>window.IPAS_BRIDGE.snapshot());
 assert.ok(reloaded.mocks.length>=1,"mock result must survive reload");
 assert.deepEqual(errors,[],"unexpected JavaScript errors");
 console.log("PASS exams: wrong answer, SRS, wrong-answer retry, mock exam, persistence");
}finally{await browser.close();}
